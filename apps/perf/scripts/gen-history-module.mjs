// Regenerates src/import/historyCsv.ts from data/historique-seances.csv so the app can import it
// offline (Metro does not bundle .csv files). Run: npm run gen:import
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const csv = fs.readFileSync(path.join(root, 'data/historique-seances.csv'), 'utf8').replace(/\r\n/g, '\n');
const body = csv.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
const out = `// GENERATED by scripts/gen-history-module.mjs from data/historique-seances.csv — do not edit.
export const HISTORY_CSV = \`${body}\`;
`;
fs.writeFileSync(path.join(root, 'src/import/historyCsv.ts'), out);
console.log(`historyCsv.ts: ${csv.trim().split('\n').length - 1} rows`);
